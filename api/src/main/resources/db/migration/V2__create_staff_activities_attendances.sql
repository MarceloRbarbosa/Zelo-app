CREATE TABLE staff_members (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    member_type   VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_staff_members_email UNIQUE (email),
    CONSTRAINT ck_staff_members_member_type CHECK (member_type IN ('VOLUNTEER', 'PROFESSIONAL', 'COORDINATOR')),
    CONSTRAINT ck_staff_members_role CHECK (role IN ('ROLE_ADMIN', 'ROLE_COORDINATOR', 'ROLE_VOLUNTEER', 'ROLE_BENEFICIARY')),
    CONSTRAINT ck_staff_members_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE activities (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(100) NOT NULL,
    description        VARCHAR(255),
    recurrence_pattern VARCHAR(50),
    lead_staff_id      BIGINT,
    status             VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    start_date         DATE         NOT NULL,
    CONSTRAINT fk_activities_lead_staff FOREIGN KEY (lead_staff_id) REFERENCES staff_members (id),
    CONSTRAINT ck_activities_status CHECK (status IN ('ACTIVE', 'FINISHED'))
);

CREATE TABLE attendances (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id     BIGINT       NOT NULL,
    beneficiary_id  BIGINT       NOT NULL,
    attendance_date DATE         NOT NULL,
    is_present      BOOLEAN      NOT NULL,
    notes           VARCHAR(255),
    CONSTRAINT fk_attendances_activity FOREIGN KEY (activity_id) REFERENCES activities (id),
    CONSTRAINT fk_attendances_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT uk_attendances_activity_beneficiary_date UNIQUE (activity_id, beneficiary_id, attendance_date)
);
