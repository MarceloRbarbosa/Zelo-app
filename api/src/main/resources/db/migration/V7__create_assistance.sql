-- Assistance items (food baskets, hygiene kits...) received by the ONG and delivered to beneficiaries.
CREATE TABLE assistance_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT true,
    CONSTRAINT uk_assistance_items_name UNIQUE (name)
);

CREATE TABLE assistance_receipts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT       NOT NULL,
    quantity    INTEGER      NOT NULL,
    received_at DATE         NOT NULL,
    donor       VARCHAR(150),
    notes       VARCHAR(255),
    recorded_by BIGINT       NOT NULL,
    CONSTRAINT fk_assistance_receipts_item FOREIGN KEY (item_id) REFERENCES assistance_items (id),
    CONSTRAINT fk_assistance_receipts_staff FOREIGN KEY (recorded_by) REFERENCES staff_members (id),
    CONSTRAINT ck_assistance_receipts_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_assistance_receipts_item ON assistance_receipts (item_id);

CREATE TABLE assistance_deliveries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        BIGINT       NOT NULL,
    beneficiary_id BIGINT       NOT NULL,
    quantity       INTEGER      NOT NULL,
    delivered_at   DATE         NOT NULL,
    notes          VARCHAR(255),
    recorded_by    BIGINT       NOT NULL,
    CONSTRAINT fk_assistance_deliveries_item FOREIGN KEY (item_id) REFERENCES assistance_items (id),
    CONSTRAINT fk_assistance_deliveries_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT fk_assistance_deliveries_staff FOREIGN KEY (recorded_by) REFERENCES staff_members (id),
    CONSTRAINT ck_assistance_deliveries_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_assistance_deliveries_item ON assistance_deliveries (item_id);
CREATE INDEX ix_assistance_deliveries_beneficiary ON assistance_deliveries (beneficiary_id, delivered_at);
