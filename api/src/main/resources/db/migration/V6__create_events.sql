-- One-off events (seminars, campaigns): responsible staff, registered beneficiaries and who attended.
CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    description TEXT,
    event_date  TIMESTAMPTZ  NOT NULL,
    location    VARCHAR(150),
    status      VARCHAR(10)  NOT NULL DEFAULT 'SCHEDULED',
    CONSTRAINT ck_events_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELED'))
);
CREATE INDEX ix_events_event_date ON events (event_date);

CREATE TABLE event_staff (
    event_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    CONSTRAINT pk_event_staff PRIMARY KEY (event_id, staff_id),
    CONSTRAINT fk_event_staff_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_event_staff_staff FOREIGN KEY (staff_id) REFERENCES staff_members (id)
);
CREATE INDEX ix_event_staff_staff ON event_staff (staff_id);

CREATE TABLE event_participants (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT      NOT NULL,
    beneficiary_id BIGINT      NOT NULL,
    registered_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    attended       BOOLEAN     NOT NULL DEFAULT false,
    CONSTRAINT fk_event_participants_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_participants_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT uk_event_participants_event_beneficiary UNIQUE (event_id, beneficiary_id)
);
CREATE INDEX ix_event_participants_beneficiary ON event_participants (beneficiary_id);
