-- Activities get weekly schedules, several responsible staff members and enrolled beneficiaries.
ALTER TABLE activities ADD COLUMN end_date DATE;
ALTER TABLE activities
    ADD CONSTRAINT ck_activities_end_date CHECK (end_date IS NULL OR end_date >= start_date);

CREATE TABLE activity_schedules (
    activity_id BIGINT      NOT NULL,
    day_of_week VARCHAR(9)  NOT NULL,
    start_time  TIME        NOT NULL,
    end_time    TIME        NOT NULL,
    CONSTRAINT fk_activity_schedules_activity FOREIGN KEY (activity_id) REFERENCES activities (id) ON DELETE CASCADE,
    CONSTRAINT uk_activity_schedules UNIQUE (activity_id, day_of_week, start_time),
    CONSTRAINT ck_activity_schedules_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_activity_schedules_time CHECK (end_time > start_time)
);

CREATE TABLE activity_staff (
    activity_id BIGINT NOT NULL,
    staff_id    BIGINT NOT NULL,
    CONSTRAINT pk_activity_staff PRIMARY KEY (activity_id, staff_id),
    CONSTRAINT fk_activity_staff_activity FOREIGN KEY (activity_id) REFERENCES activities (id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_staff_staff FOREIGN KEY (staff_id) REFERENCES staff_members (id)
);
CREATE INDEX ix_activity_staff_staff ON activity_staff (staff_id);

-- The single lead becomes the first responsible member; the free-text recurrence is replaced by schedules.
INSERT INTO activity_staff (activity_id, staff_id)
SELECT id, lead_staff_id FROM activities WHERE lead_staff_id IS NOT NULL;
ALTER TABLE activities DROP COLUMN lead_staff_id;
ALTER TABLE activities DROP COLUMN recurrence_pattern;

CREATE TABLE enrollments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id    BIGINT      NOT NULL,
    beneficiary_id BIGINT      NOT NULL,
    status         VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    left_at        DATE,
    CONSTRAINT fk_enrollments_activity FOREIGN KEY (activity_id) REFERENCES activities (id),
    CONSTRAINT fk_enrollments_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT uk_enrollments_activity_beneficiary UNIQUE (activity_id, beneficiary_id),
    CONSTRAINT ck_enrollments_status CHECK (status IN ('ACTIVE', 'LEFT')),
    CONSTRAINT ck_enrollments_left_at CHECK ((status = 'LEFT') = (left_at IS NOT NULL))
);
CREATE INDEX ix_enrollments_beneficiary ON enrollments (beneficiary_id);
