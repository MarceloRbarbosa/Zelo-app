-- Every beneficiary has a CPF. A beneficiary anonymized on request (LGPD) keeps only the id, so attendance
-- and delivery history stay counted without identifying the person.
ALTER TABLE beneficiaries DROP CONSTRAINT ck_beneficiaries_status;
ALTER TABLE beneficiaries
    ADD CONSTRAINT ck_beneficiaries_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'ANONYMIZED'));
ALTER TABLE beneficiaries ALTER COLUMN birth_date DROP NOT NULL;
ALTER TABLE beneficiaries ALTER COLUMN phone_number DROP NOT NULL;
ALTER TABLE beneficiaries
    ADD CONSTRAINT ck_beneficiaries_personal_data CHECK (status = 'ANONYMIZED'
        OR (document_number IS NOT NULL AND birth_date IS NOT NULL AND phone_number IS NOT NULL));

-- Proof that a removal request was fulfilled: when and by whom, with no personal data.
CREATE TABLE data_removals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id BIGINT       NOT NULL,
    removed_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    removed_by     BIGINT       NOT NULL,
    note           VARCHAR(255),
    CONSTRAINT fk_data_removals_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT fk_data_removals_staff FOREIGN KEY (removed_by) REFERENCES staff_members (id)
);
