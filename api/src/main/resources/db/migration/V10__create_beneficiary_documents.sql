-- Files attached to a beneficiary (school certificates, proof of address...). The bytes live in the
-- documents directory under storage_key; the table keeps what is needed to list and serve them.
CREATE TABLE beneficiary_documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id BIGINT       NOT NULL,
    title          VARCHAR(100) NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    content_type   VARCHAR(50)  NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    storage_key    VARCHAR(64)  NOT NULL,
    uploaded_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    uploaded_by    BIGINT       NOT NULL,
    CONSTRAINT fk_beneficiary_documents_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (id),
    CONSTRAINT fk_beneficiary_documents_staff FOREIGN KEY (uploaded_by) REFERENCES staff_members (id),
    CONSTRAINT uk_beneficiary_documents_storage_key UNIQUE (storage_key)
);
CREATE INDEX ix_beneficiary_documents_beneficiary ON beneficiary_documents (beneficiary_id);
